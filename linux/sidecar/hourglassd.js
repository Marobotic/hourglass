#!/usr/bin/env node
// Hourglass desktop sidecar (Linux and Windows). Holds the local replica,
// serves the app and local AIs on 127.0.0.1, rings alarms and timers, and
// syncs with the server.
//   config: ~/.config/hourglass/config.json   (Windows: %APPDATA%\Hourglass)
//   data:   ~/.local/share/hourglass/         (Windows: %LOCALAPPDATA%\Hourglass)
//   config.json: { "server": "https://...", "token": "..." }
import { createServer } from "node:http";
import { randomBytes } from "node:crypto";
import { spawn, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { Store } from "../../core/node/store.js";
import { Service } from "../../core/node/service.js";
import { BUILTIN_RINGTONES, TABLE_NAMES, dueBetween, isSpent, localParts, parseDate } from "../../core/index.js";
import { createHandler } from "../../server/app.js";

const HOME = homedir();
const WIN = process.platform === "win32";
const CONF_DIR = process.env.HOURGLASS_CONFIG || (WIN ? join(process.env.APPDATA || HOME, "Hourglass") : join(HOME, ".config/hourglass"));
const DATA_DIR = process.env.HOURGLASS_DATA || (WIN ? join(process.env.LOCALAPPDATA || HOME, "Hourglass") : join(HOME, ".local/share/hourglass"));
const PORT = Number(process.env.HOURGLASS_PORT || 8931);
const THEME = join(HOME, ".local/state/omarchy/current/theme/colors.toml");
// Ringtones ship in assets/sounds (generated by make-sounds.py).
// Uploads and songs are synced rows whose audio is downloaded to data/sounds.
const SOUNDS_DIR = join(import.meta.dirname, "../../assets/sounds");
const CUSTOM_DIR = join(DATA_DIR, "sounds");
const customFile = (id) => join(CUSTOM_DIR, `${id}.wav`);
const soundFile = (name) => {
  if (BUILTIN_RINGTONES.includes(name)) return join(SOUNDS_DIR, `${name}.wav`);
  if (/^[0-9a-f-]{36}$/.test(name ?? "") && existsSync(customFile(name))) return customFile(name);
  return join(SOUNDS_DIR, "classic.wav");
};
const SILENT = process.env.HOURGLASS_SILENT === "1"; // tests: no notification, no sound
mkdirSync(CONF_DIR, { recursive: true });

// Single-quoted PowerShell string literal.
const psq = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);

function token() {
  const p = join(CONF_DIR, "token");
  if (existsSync(p)) return readFileSync(p, "utf8").trim();
  const t = randomBytes(24).toString("base64url");
  writeFileSync(p, t + "\n", { mode: 0o600 });
  return t;
}

// The sync server is built in. Sign-in is the Omarchy Music account: its
// session is the bearer. Credentials never sit on disk in plain text: Linux
// keeps them in the Secret Service keyring (GNOME Keyring), Windows in DPAPI
// blobs only this Windows user can decrypt. On Linux a signed-in Omarchy
// Music player is picked up automatically. The legacy sync token (shipped
// once in config.json or HOURGLASS_PROVISION) still works until you sign in.
const SERVER = process.env.HOURGLASS_SERVER || "https://marobotic.dev/hourglass";
const MUSIC_SETTINGS = join(HOME, ".config/omarchy/maro-music/settings.json");
const CONFIG_FILE = join(CONF_DIR, "config.json");
const dpapiFile = (key) => join(CONF_DIR, key === "sync-token" ? "sync.dpapi" : `${key}.dpapi`);

function keyringGet(key) {
  if (WIN) {
    if (!existsSync(dpapiFile(key))) return null;
    const r = spawnSync("powershell.exe", ["-NoProfile", "-Command",
      `$s = Get-Content -Raw ${psq(dpapiFile(key))} | ConvertTo-SecureString; [Runtime.InteropServices.Marshal]::PtrToStringUni([Runtime.InteropServices.Marshal]::SecureStringToBSTR($s))`], { encoding: "utf8", windowsHide: true });
    return r.status === 0 ? r.stdout.trim() || null : null;
  }
  const r = spawnSync("secret-tool", ["lookup", "service", "hourglass", "key", key], { encoding: "utf8" });
  return r.status === 0 ? r.stdout.trim() || null : null;
}

function keyringSet(key, value) {
  if (WIN) {
    const r = spawnSync("powershell.exe", ["-NoProfile", "-Command",
      `ConvertTo-SecureString ${psq(value)} -AsPlainText -Force | ConvertFrom-SecureString | Set-Content -NoNewline ${psq(dpapiFile(key))}`], { windowsHide: true });
    return r.status === 0;
  }
  const r = spawnSync("secret-tool", ["store", `--label=Hourglass ${key}`, "service", "hourglass", "key", key], { input: value });
  return r.status === 0;
}

function keyringClear(key) {
  if (WIN) return rmSync(dpapiFile(key), { force: true });
  spawnSync("secret-tool", ["clear", "service", "hourglass", "key", key]);
}

const readConfig = () => {
  try { return JSON.parse(readFileSync(CONFIG_FILE, "utf8")); } catch { return {}; }
};
const writeConfig = (cfg) => writeFileSync(CONFIG_FILE, JSON.stringify(cfg, null, 2) + "\n", { mode: 0o600 });

// Move a provisioned token into the keyring and scrub it from config.json.
function adoptToken() {
  const cfg = readConfig();
  const incoming = process.env.HOURGLASS_PROVISION || cfg.token;
  if (incoming && keyringSet("sync-token", incoming)) {
    delete cfg.token;
    delete cfg.server;
    writeConfig(cfg);
    log("sync token moved into the keyring");
  }
}

let cred = null; // { token, kind: "session" | "token" }
const config = () => {
  if (!cred) {
    const session = keyringGet("session");
    const legacy = session ? null : keyringGet("sync-token");
    cred = session ? { token: session, kind: "session" } : legacy ? { token: legacy, kind: "token" } : { token: null, kind: null };
  }
  return cred.token ? { server: SERVER, token: cred.token } : {};
};

adoptToken();
const SCHEMA = 4; // bump when a table is added: forces one full pull
const store = new Store(join(DATA_DIR, "hourglass.db"), { replica: true });
const service = new Service(store);
const TOKEN = token();
if (store.meta("schema", 1) !== SCHEMA) {
  store.setMeta("cursor", 0);
  store.setMeta("schema", SCHEMA);
}
mkdirSync(CUSTOM_DIR, { recursive: true });

// --- account ---------------------------------------------------------------------

async function remote(path, { method = "GET", body, bearer = config().token, raw } = {}) {
  const headers = bearer ? { authorization: `Bearer ${bearer}` } : {};
  if (body !== undefined && !raw) headers["content-type"] = "application/json";
  const r = await fetch(SERVER + path, { method, headers, body: raw ?? (body === undefined ? undefined : JSON.stringify(body)), signal: AbortSignal.timeout(raw ? 120000 : 15000) });
  const out = await r.json().catch(() => ({}));
  if (!r.ok) throw Object.assign(new Error(out.error || `server ${r.status}`), { status: r.status < 500 ? r.status : 502 });
  return out;
}

// Local data belongs to one account: signing in as someone else starts clean.
function useAccount(email) {
  const was = store.meta("account", null);
  if (was && email && was !== email) {
    for (const t of TABLE_NAMES) store.db.exec(`DELETE FROM ${t}`);
    for (const f of readdirSync(CUSTOM_DIR)) rmSync(join(CUSTOM_DIR, f), { force: true });
    store.setMeta("cursor", 0);
    dirtyUpcoming = true;
    log("switched account: local data cleared");
  }
  store.setMeta("account", email || null);
}

async function signIn(session, email) {
  keyringSet("session", session);
  keyringClear("sync-token");
  cred = null;
  const cfg = readConfig();
  delete cfg.signed_out;
  writeConfig(cfg);
  useAccount(email);
  await syncOnce();
  return account();
}

async function signOut() {
  const { token: t } = config();
  if (cred?.kind === "session") await remote("/auth/logout", { method: "POST", bearer: t }).catch(() => {});
  keyringClear("session");
  keyringClear("sync-token");
  cred = null;
  writeConfig({ ...readConfig(), signed_out: true });
  Object.assign(sync, { state: "local", error: null });
  return account();
}

// A signed-in Omarchy Music player on this PC signs Hourglass in too.
async function adoptMusicSession() {
  if (WIN || cred?.kind === "session" || readConfig().signed_out) return;
  let session;
  try { session = JSON.parse(readFileSync(MUSIC_SETTINGS, "utf8")).account_session; } catch { return; }
  if (!session) return;
  try {
    const { email } = await remote("/api/account", { bearer: session });
    log("signed in with the Omarchy Music account", email);
    await signIn(session, email);
  } catch (e) {
    log("music session not usable:", e.message);
  }
}

const account = () => ({ email: store.meta("account", null), signed_in: cred?.kind === "session", legacy: cred?.kind === "token", server: SERVER });

// --- theme ---------------------------------------------------------------------

const FALLBACK = { background: "#121212", foreground: "#f5f5f5", accent: "#B14242", color1: "#D66E36", color3: "#F0BE66", color4: "#4A8B8B", color8: "#949494" };
function theme() {
  const t = { ...FALLBACK };
  try {
    for (const line of readFileSync(THEME, "utf8").split("\n")) {
      const m = line.match(/^\s*([a-z0-9_]+)\s*=\s*"(#[0-9a-fA-F]{6})"/);
      if (m) t[m[1]] = m[2];
    }
  } catch {}
  return t;
}

// --- sync ------------------------------------------------------------------------

const sync = { state: "local", last_ok: null, error: null, pending: 0 };

async function syncOnce() {
  const { server, token: remoteToken } = config();
  const dirty = store.dirtyRows();
  sync.pending = TABLE_NAMES.reduce((n, t) => n + dirty[t].length, 0);
  if (!server) {
    sync.state = "signed_out";
    return;
  }
  const headers = { authorization: `Bearer ${remoteToken}`, "content-type": "application/json" };
  try {
    if (sync.pending) {
      const body = { changes: Object.fromEntries(TABLE_NAMES.map((t) => [t, dirty[t].map((r) => ({ ...r, base_rev: r.rev }))])) };
      const r = await fetch(`${server}/api/sync`, { method: "POST", headers, body: JSON.stringify(body), signal: AbortSignal.timeout(15000) });
      if (!r.ok) throw new Error(`push ${r.status}`);
      const { revs = {} } = await r.json();
      for (const t of TABLE_NAMES) for (const row of dirty[t]) {
        if (revs[t]?.[row.id] != null) store.setRev(t, row.id, revs[t][row.id]);
        store.clearDirty(t, row.id, row.updated_at);
      }
    }
    const since = store.meta("cursor", 0);
    const r = await fetch(`${server}/api/sync?since=${since}`, { headers, signal: AbortSignal.timeout(15000) });
    if (!r.ok) throw new Error(`pull ${r.status}`);
    const { rev, changes } = await r.json();
    for (const t of TABLE_NAMES) for (const row of changes[t] ?? []) store.write(t, row, { mode: "remote" });
    store.setMeta("cursor", rev);
    Object.assign(sync, { state: "synced", last_ok: Date.now(), error: null, pending: 0 });
    if (!store.meta("account", null)) store.setMeta("account", (await remote("/api/account")).email);
    await fetchSounds();
  } catch (e) {
    Object.assign(sync, { state: / 401$/.test(e.message) ? "signed_out" : "offline", error: e.message });
  }
}

// Download the audio of every synced ringtone; drop files of deleted ones.
async function fetchSounds() {
  const want = new Set();
  for (const r of store.all("ringtones")) {
    want.add(`${r.id}.wav`);
    if (existsSync(customFile(r.id))) continue;
    try {
      const res = await fetch(`${SERVER}/api/ringtones/${r.id}/audio`, { headers: { authorization: `Bearer ${config().token}` }, signal: AbortSignal.timeout(60000) });
      if (!res.ok) continue;
      writeFileSync(customFile(r.id) + ".part", Buffer.from(await res.arrayBuffer()));
      renameSync(customFile(r.id) + ".part", customFile(r.id));
    } catch {}
  }
  for (const f of readdirSync(CUSTOM_DIR)) if (!want.has(f)) rmSync(join(CUSTOM_DIR, f), { force: true });
}

let syncTimer = null;
const scheduleSync = (ms = 1500) => {
  clearTimeout(syncTimer);
  syncTimer = setTimeout(syncOnce, ms);
};
store.onChange((_, row) => row.dirty && scheduleSync());
setInterval(() => scheduleSync(0), 30000);

// --- alarms & timers ------------------------------------------------------------------

const ringing = new Map(); // id -> { kind, id, label, at, sound }
let lastCheck = Date.now();

function notify(item) {
  if (SILENT) return;
  const title = item.kind === "timer" ? "Timer done" : "Alarm";
  if (WIN) {
    // A tray balloon shows as a regular Windows notification on 10 and 11.
    const ps = `Add-Type -AssemblyName System.Windows.Forms; $n = New-Object System.Windows.Forms.NotifyIcon; ` +
      `$n.Icon = [System.Drawing.SystemIcons]::Information; $n.Visible = $true; ` +
      `$n.ShowBalloonTip(15000, ${psq(title)}, ${psq(item.label)}, 'Info'); Start-Sleep -Seconds 16; $n.Dispose()`;
    spawn("powershell.exe", ["-NoProfile", "-WindowStyle", "Hidden", "-Command", ps], { stdio: "ignore", windowsHide: true }).on("error", () => {});
    return;
  }
  const n = spawn("notify-send", ["-a", "Hourglass", "-u", "critical", "-i", "alarm-symbolic", "-h", "string:x-canonical-private-synchronous:hourglass-" + item.id, title, item.label], { stdio: "ignore" });
  n.on("error", () => {});
}

function playOnce(file) {
  const c = WIN
    ? spawn("powershell.exe", ["-NoProfile", "-Command", `(New-Object Media.SoundPlayer ${psq(file)}).PlaySync()`], { stdio: "ignore", windowsHide: true })
    : spawn("pw-play", [file], { stdio: "ignore" });
  c.on("error", () => {});
  return c;
}

function playLoop(item) {
  if (SILENT || service.settings().sound === false) return () => {};
  let stopped = false;
  let child = null;
  const until = Date.now() + 60000;
  const once = () => {
    if (stopped || Date.now() > until) return ring_stop(item.id);
    child = playOnce(soundFile(service.settings().ringtone));
    child.on("error", () => {});
    child.on("exit", () => setTimeout(once, 400));
  };
  once();
  return () => {
    stopped = true;
    child?.kill();
  };
}

function ring(item) {
  if (ringing.has(item.id)) return;
  log("ring", item.kind, item.label);
  notify(item);
  ringing.set(item.id, { ...item, stop: playLoop(item) });
  const data = service.data();
  if (item.kind === "timer") service.updateTimer({ timer_id: item.id, action: "done" });
  if (item.kind === "alarm") {
    const a = data.alarms.find((x) => x.id === item.id);
    if (a && isSpent(a, data, Date.now() + 1000, service.tz)) store.upsert("alarms", { id: a.id, enabled: 0 });
  }
}

function ring_stop(id) {
  const r = ringing.get(id);
  if (!r) return false;
  r.stop();
  ringing.delete(id);
  return true;
}

// What rings in the next 36 h, recomputed once a minute and after any change;
// the per-second check only compares timestamps. (Recomputing every second
// expanded every recurrence and cost ~30% CPU.)
let upcoming = [];
let dirtyUpcoming = true;
function refreshUpcoming(now) {
  upcoming = dueBetween(service.data(), Math.max(lastCheck, now - 10 * 60000), now + 36 * 3600000, service.tz);
  dirtyUpcoming = false;
}
store.onChange(() => { dirtyUpcoming = true; });
setInterval(() => { dirtyUpcoming = true; }, 60000);

setInterval(() => {
  const now = Date.now();
  if (now - lastCheck > 5 * 60000) dirtyUpcoming = true; // woke from suspend
  if (dirtyUpcoming) refreshUpcoming(now);
  // ring what fell due since the last check, but nothing older than 10 min
  const from = Math.max(lastCheck, now - 10 * 60000);
  for (const item of upcoming) if (item.at > from && item.at <= now) ring(item);
  lastCheck = now;
}, 1000);

// Minutes the user's zone is ahead of UTC right now; the QML clock uses it so
// the app shows Hourglass time even when the system zone differs.
function tzOffsetMin() {
  const now = Date.now();
  const p = localParts(now, service.tz);
  return Math.round((parseDate(p.date) + p.minutes * 60000 + p.seconds * 1000 - now) / 60000);
}

// --- HTTP ------------------------------------------------------------------------

const json = (res, status, body) => {
  res.writeHead(status, { "content-type": "application/json", "cache-control": "no-store" });
  res.end(JSON.stringify(body));
};

async function extra(req, res, url, path) {
  if (path === "/api/app" && req.method === "GET") {
    return json(res, 200, {
      theme: theme(),
      sync: { ...sync, server: config().server ?? null },
      ringing: [...ringing.values()].map(({ stop, ...r }) => r),
      settings: service.settings(),
      account: account(),
      tz_offset_min: tzOffsetMin(),
    }), true;
  }
  if (path === "/api/ring/stop" && req.method === "POST") {
    const id = url.searchParams.get("id");
    const ids = id ? [id] : [...ringing.keys()];
    return json(res, 200, { stopped: ids.filter(ring_stop) }), true;
  }
  if (path === "/api/ring/snooze" && req.method === "POST") {
    const id = url.searchParams.get("id");
    const r = ringing.get(id);
    if (!r) return json(res, 404, { error: "not ringing" }), true;
    ring_stop(id);
    const t = service.startTimer({ minutes: Number(url.searchParams.get("minutes") || 5), label: `${r.label} (snoozed)` });
    return json(res, 200, t), true;
  }
  if (path === "/api/account" && req.method === "GET") return json(res, 200, account()), true;
  if (path === "/api/account/login" && req.method === "POST") {
    const b = await readBody(req);
    const out = await remote("/auth/login", { method: "POST", body: { email: b.email, password: b.password }, bearer: null });
    return json(res, 200, await signIn(out.session, out.email)), true;
  }
  if (path === "/api/account/register" && req.method === "POST") {
    const b = await readBody(req);
    const out = await remote("/auth/register", { method: "POST", body: { email: b.email, password: b.password }, bearer: null });
    if (!out.session) throw Object.assign(new Error("account created: sign in with it"), { status: 400 });
    return json(res, 200, await signIn(out.session, out.email || String(b.email).toLowerCase())), true;
  }
  // The account's personal AI key and links (made on the server).
  if (path === "/api/ai" && (req.method === "GET" || req.method === "POST")) {
    return json(res, 200, await remote("/api/ai", { method: req.method, body: req.method === "POST" ? {} : undefined })), true;
  }
  if (path === "/api/account/logout" && req.method === "POST") return json(res, 200, await signOut()), true;
  if (path === "/api/ringtones" && req.method === "GET") {
    return json(res, 200, service.listRingtones().map((r) => ({ ...r, ready: r.kind === "builtin" || existsSync(customFile(r.id)) }))), true;
  }
  // Upload a local audio file: the server cuts and stores it, then it syncs here.
  if (path === "/api/ringtones/upload" && req.method === "POST") {
    const b = await readBody(req);
    const file = decodeURIComponent(String(b.path || "").replace(/^file:\/\//, ""));
    if (!existsSync(file)) return json(res, 400, { error: "file not found" }), true;
    const name = b.name || file.split(/[\\/]/).pop();
    const row = await remote(`/api/ringtones/upload?select=1&name=${encodeURIComponent(name)}`, { method: "POST", raw: readFileSync(file) });
    await syncOnce();
    return json(res, 201, row), true;
  }
  const del = /^\/api\/ringtones\/([0-9a-f-]{36})$/.exec(path);
  if (del && req.method === "DELETE") return json(res, 200, service.removeRingtone({ ringtone_id: del[1] })), true;
  // Plays a ringtone once, for choosing one in Settings.
  if (path === "/api/ring/preview" && req.method === "POST") {
    playOnce(soundFile(url.searchParams.get("name")));
    return json(res, 200, { ok: true }), true;
  }
  if (path === "/api/sync/now" && req.method === "POST") {
    await syncOnce();
    return json(res, 200, sync), true;
  }
  return false;
}

async function readBody(req) {
  let b = "";
  for await (const c of req) b += c;
  try { return JSON.parse(b || "{}"); } catch { return {}; }
}

const handler = createHandler({ store, service, token: TOKEN, extra });
createServer(handler).listen(PORT, "127.0.0.1", async () => {
  log(`hourglassd on http://127.0.0.1:${PORT} (data ${DATA_DIR}, tz ${service.tz})`);
  config();
  await adoptMusicSession();
  scheduleSync(0);
});

for (const sig of ["SIGINT", "SIGTERM"]) process.on(sig, () => {
  for (const id of [...ringing.keys()]) ring_stop(id);
  process.exit(0);
});
