// The server's terse errors, in words for the window's toast and sign-in page.
function remoteError(status, out, signedIn) {
  if (status === 401 && out.error === "unauthorized") return signedIn ? "Your sign-in has expired. Sign in again." : "The server turned that down. Try again in a moment.";
  if (status === 401 && /invalid email or password/.test(out.error)) return "Wrong email or password.";
  if (status === 409 && /already registered/.test(out.error)) return "That email already has an account. Sign in instead.";
  if (status === 429) return out.retryIn ? `Too many attempts. Try again in ${out.retryIn} seconds.` : "Too many attempts. Try again in a minute.";
  if (status >= 500) return out.error || "The Hourglass server had a problem. Try again in a moment.";
  return out.error || `server ${status}`;
}

async function remote(path, { method = "GET", body, bearer = config().token, raw } = {}) {
  // Signed out: only sign-in itself goes to the server.
  if (!bearer && !path.startsWith("/auth/")) throw Object.assign(new Error("Sign in to Hourglass first."), { status: 401 });
  const headers = bearer ? { authorization: `Bearer ${bearer}` } : {};
  if (body !== undefined && !raw) headers["content-type"] = "application/json";
  let r;
  // A dropped connection (the server restarted, a kept-alive socket went stale)
  // fails at once: try once more before telling anyone.
  for (let attempt = 0; ; attempt++) {
    try {
      r = await fetch(SERVER + path, { method, headers, body: raw ?? (body === undefined ? undefined : JSON.stringify(body)), signal: AbortSignal.timeout(raw ? 120000 : 15000) });
      break;
    } catch (e) {
      const slow = e.name === "TimeoutError";
      if (!slow && attempt === 0) { await new Promise((ok) => setTimeout(ok, 800)); continue; }
      log(`server ${method} ${path}: ${e.cause?.code || e.cause?.message || e.message}`);
      throw Object.assign(new Error(slow ? "The Hourglass server took too long to answer. Try again in a moment." : "Can't connect to the Hourglass server right now. Check that this computer is online, then try again."), { status: slow ? 504 : 503 });
    }
  }
  const out = await r.json().catch(() => ({}));
  if (r.status === 401 && bearer && bearer === cred?.token && !path.startsWith("/auth/")) endSession();
  if (!r.ok) throw Object.assign(new Error(remoteError(r.status, out, !!bearer)), { status: r.status < 500 ? r.status : 502 });
  return out;
}

// Local data belongs to one account: signing in as someone else starts clean.
function useAccount(email) {
  const was = store.meta("account", null);
  if (was && email && was !== email) {
    for (const t of TABLE_NAMES) store.db.exec(`DELETE FROM ${t}`);
    for (const f of readdirSync(CUSTOM_DIR)) rmSync(join(CUSTOM_DIR, f), { force: true });
    store.setMeta("cursor", 0);
    dirtyUpcoming = true;
    log("switched account: local data cleared");
  }
  store.setMeta("account", email || null);
}

// The server says 401 only when the account server turned the session down (a
// password change or reset ends every session), so it is gone for good: drop it
// and show the sign-in page instead of failing quietly forever. The account name
// and local data stay, so signing in again with it sends the unsynced changes.
function endSession() {
  if (cred?.kind !== "session" && cred?.kind !== "token") return;
  log("the server ended this sign-in; showing the sign-in page");
  keyringClear("session");
  keyringClear("sync-token");
  cred = null;
  sessionEnded = "You were signed out, usually because the password was changed. Sign in again: nothing on this computer is lost.";
  Object.assign(sync, { state: "signed_out" });
}

async function signIn(session, email) {
  sessionEnded = null;
  keyringSet("session", session);
  keyringClear("sync-token");
  cred = null;
  const cfg = readConfig();
  delete cfg.signed_out;
  writeConfig(cfg);
  useAccount(email);
  await syncOnce();
  return account();
}

async function signOut() {
  const { token: t } = config();
  if (cred?.kind === "session") await remote("/auth/logout", { method: "POST", bearer: t }).catch(() => {});
  keyringClear("session");
  keyringClear("sync-token");
  cred = null;
  writeConfig({ ...readConfig(), signed_out: true });
  Object.assign(sync, { state: "local", error: null });
  return account();
}

// A signed-in Jukebox player on this PC signs Hourglass in too.
async function adoptMusicSession() {
  if (WIN || cred?.kind === "session" || readConfig().signed_out) return;
  let session;
  try { session = JSON.parse(readFileSync(MUSIC_SETTINGS, "utf8")).account_session; } catch { return; }
  if (!session) return;
  try {
    const { email } = await remote("/api/account", { bearer: session });
    log("signed in with the Jukebox account", email);
    await signIn(session, email);
  } catch (e) {
    log("music session not usable:", e.message);
  }
}

