// --- drive -------------------------------------------------------------------------
//
// Files live on the server; this computer keeps a copy of every file it has
// uploaded or opened, as DRIVE_DIR/<id>/<its real name> so the system opens
// it with the right app (Photos for .jpg, Illustrator for .ai). index.json
// records what each copy was: the row's updated_at and the copy's mtime/size.
// Every few seconds the copies are checked:
//   * edited here (newer mtime, size settled): uploaded again (PUT .../raw);
//   * changed on another device (row updated_at moved on): downloaded again;
//   * deleted anywhere: removed.

const fetching = new Map(); // id -> promise, so one file is downloaded once
const INDEX = join(DRIVE_DIR, "index.json");
let index = {};
try { index = JSON.parse(readFileSync(INDEX, "utf8")); } catch {}
// Copies from before files kept their names were plain DRIVE_DIR/<id>: drop
// them (they come back on demand, named).
try {
  for (const n of readdirSync(DRIVE_DIR)) if (/^[0-9a-f-]{36}$/.test(n) && statSync(join(DRIVE_DIR, n)).isFile()) rmSync(join(DRIVE_DIR, n), { force: true });
} catch {}
const saveIndex = () => { mkdirSync(DRIVE_DIR, { recursive: true }); writeFileSync(INDEX, JSON.stringify(index)); };
const safeName = (n) => String(n || "file").replace(/[<>:"/\\|?*\x00-\x1f]/g, "_").replace(/[. ]+$/, "") || "file";
const copyPath = (row) => join(DRIVE_DIR, row.id, safeName(row.name));

function remember(row, path) {
  const st = statSync(path);
  index[row.id] = { name: row.name, path, updated_at: row.updated_at, mtime: st.mtimeMs, size: st.size };
  saveIndex();
}

async function download(row) {
  const { server, token } = config();
  if (!server) throw Object.assign(new Error("sign in to open files"), { status: 401 });
  const r = await fetch(`${server}/api/files/${row.id}/raw`, { headers: { authorization: `Bearer ${token}` }, signal: AbortSignal.timeout(3600000) });
  if (!r.ok) throw Object.assign(new Error(`could not download (${r.status})`), { status: 502 });
  const f = copyPath(row);
  mkdirSync(dirname(f), { recursive: true });
  const tmp = join(DRIVE_DIR, row.id + ".part");
  await pipeline(Readable.fromWeb(r.body), createWriteStream(tmp));
  // A renamed file: drop the copy under the old name.
  const old = index[row.id]?.path;
  if (old && old !== f) rmSync(old, { force: true });
  renameSync(tmp, f);
  remember(row, f);
  return f;
}

// The file's bytes on this computer, downloaded from the server when needed.
async function localFile(id) {
  if (!/^[0-9a-f-]{36}$/.test(id)) throw Object.assign(new Error("bad id"), { status: 400 });
  const row = store.get("files", id);
  if (!row || row.deleted) throw Object.assign(new Error("no such file"), { status: 404 });
  const have = index[id];
  if (have && existsSync(have.path) && (have.updated_at >= row.updated_at || edited(have))) return { row, path: have.path };
  if (!fetching.has(id)) fetching.set(id, download(row).finally(() => fetching.delete(id)));
  return { row, path: await fetching.get(id) };
}

const edited = (have) => { try { return statSync(have.path).mtimeMs > have.mtime + 1; } catch { return false; } };

const settling = new Map(); // id -> size seen last tick, for edits still being written
let watching = false;
async function watchDrive() {
  if (watching) return;
  watching = true;
  try {
    for (const [id, have] of Object.entries(index)) {
      const row = store.get("files", id);
      if (!row || row.deleted) {
        rmSync(join(DRIVE_DIR, id), { recursive: true, force: true });
        delete index[id];
        saveIndex();
        continue;
      }
      let st;
      try { st = statSync(have.path); } catch { delete index[id]; saveIndex(); continue; }
      if (st.mtimeMs > have.mtime + 1) {
        // Edited here. Wait until the size holds still for one tick (apps
        // write big files in several goes), then send it.
        if (settling.get(id) !== st.size) { settling.set(id, st.size); continue; }
        settling.delete(id);
        const { server, token } = config();
        if (!server) continue;
        try {
          const r = await fetch(`${server}/api/files/${id}/raw`, {
            method: "PUT",
            headers: { authorization: `Bearer ${token}`, "content-type": "application/octet-stream", "content-length": String(st.size) },
            body: createReadStream(have.path),
            duplex: "half",
            signal: AbortSignal.timeout(3600000),
          });
          if (!r.ok) throw new Error(`upload ${r.status}`);
          const out = await r.json();
          store.write("files", out, { mode: "remote" });
          remember(out, have.path);
          log("uploaded edited file", row.name);
        } catch (e) {
          log("could not upload edited", row.name, e.message); // tried again next tick (the file is still newer)
        }
      } else if (row.updated_at > have.updated_at && row.name !== have.name) {
        // Renamed elsewhere: same bytes, new name on disk.
        const f = copyPath(row);
        try { renameSync(have.path, f); remember(row, f); } catch {}
      } else if (row.updated_at > have.updated_at && !fetching.has(id)) {
        // Changed on another device: fetch the new contents.
        fetching.set(id, download(row).catch((e) => log("refresh failed", row.name, e.message)).finally(() => fetching.delete(id)));
      }
    }
  } finally {
    watching = false;
  }
}
setInterval(() => watchDrive().catch((e) => log("drive watch:", e.message)), 3000);

// GET /thumbs/<id>?k=<FILE_KEY>: a small JPEG for the file list, made on the
// server, so listing a folder never downloads the files in it. Kept in
// data/thumbs under the row's updated_at; a newer one replaces it.
const THUMB_DIR = join(DATA_DIR, "thumbs");
const thumbing = new Map();
async function serveThumb(req, res, url) {
  const m = /^\/thumbs\/([0-9a-f-]{36})$/.exec(url.pathname);
  if (!m || url.searchParams.get("k") !== FILE_KEY) return json(res, 403, { error: "forbidden" });
  const row = store.get("files", m[1]);
  if (!row || row.deleted) return json(res, 404, { error: "not found" });
  const f = join(THUMB_DIR, `${row.id}.${String(row.updated_at).replace(/[^0-9a-zA-Z]/g, "")}.jpg`);
  try {
    if (!existsSync(f)) {
      if (!thumbing.has(f)) thumbing.set(f, (async () => {
        const { server, token } = config();
        if (!server) throw Object.assign(new Error("signed out"), { status: 401 });
        const r = await fetch(`${server}/api/files/${row.id}/thumb`, { headers: { authorization: `Bearer ${token}` }, signal: AbortSignal.timeout(60000) });
        if (!r.ok) throw Object.assign(new Error("no preview"), { status: 404 });
        mkdirSync(THUMB_DIR, { recursive: true });
        for (const n of readdirSync(THUMB_DIR)) if (n.startsWith(row.id + ".")) rmSync(join(THUMB_DIR, n), { force: true });
        writeFileSync(f, Buffer.from(await r.arrayBuffer()));
      })().finally(() => thumbing.delete(f)));
      await thumbing.get(f);
    }
    res.writeHead(200, { "content-type": "image/jpeg", "content-length": statSync(f).size, "cache-control": "private, max-age=60" });
    createReadStream(f).pipe(res);
  } catch (e) {
    json(res, e.status || 500, { error: e.message });
  }
}

// GET /files/<id>?k=<FILE_KEY>: the bytes, for pictures and videos in the
// window (with Range, so a video can seek). No API token.
async function serveFile(req, res, url) {
  const m = /^\/files\/([0-9a-f-]{36})$/.exec(url.pathname);
  if (!m || url.searchParams.get("k") !== FILE_KEY) return json(res, 403, { error: "forbidden" });
  try {
    const { row, path } = await localFile(m[1]);
    const size = statSync(path).size;
    const range = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range || "");
    const head = { "content-type": row.mime || "application/octet-stream", "accept-ranges": "bytes", "cache-control": "private, max-age=60" };
    if (range && size) {
      const start = range[1] ? +range[1] : size - +range[2];
      const end = range[1] && range[2] ? Math.min(+range[2], size - 1) : size - 1;
      res.writeHead(206, { ...head, "content-range": `bytes ${start}-${end}/${size}`, "content-length": end - start + 1 });
      return createReadStream(path, { start, end }).pipe(res);
    }
    res.writeHead(200, { ...head, "content-length": size });
    createReadStream(path).pipe(res);
  } catch (e) {
    json(res, e.status || 500, { error: e.message });
  }
}

async function driveRoutes(req, res, url, path) {
  const m = req.method;
  if (path === "/api/drive/info" && m === "GET") return json(res, 200, { file_base: `http://127.0.0.1:${PORT}/files/`, thumb_base: `http://127.0.0.1:${PORT}/thumbs/`, key: FILE_KEY }), true;
  if (path === "/api/drive/usage" && m === "GET") return json(res, 200, await remote("/api/drive/usage")), true;
  // Upload a file from this computer: { path, folder, course, note }. Streams to the server.
  if (path === "/api/files/upload" && m === "POST") {
    const b = await readBody(req);
    const file = decodeURIComponent(String(b.path || "").replace(/^file:\/\/\/?/, WIN ? "" : "/"));
    if (!existsSync(file)) return json(res, 400, { error: "file not found" }), true;
    const { server, token } = config();
    if (!server) return json(res, 401, { error: "sign in to upload" }), true;
    // Too big for one upload (the server says how big): say so before sending.
    const max = (await remote("/api/drive/usage").catch(() => null))?.max_file;
    if (max && statSync(file).size > max) {
      return json(res, 413, { error: `${file.split(/[\\/]/).pop()} is over ${Math.round(max / 1048576)} MB, the most one upload can be.` }), true;
    }
    // A folder or note made a moment ago must reach the server first.
    await syncOnce();
    const name = file.split(/[\\/]/).pop();
    const q = new URLSearchParams({ name });
    if (b.folder) q.set("folder", b.folder);
    if (b.course) q.set("course", b.course);
    if (b.note) q.set("note", b.note);
    const r = await fetch(`${server}/api/files/upload?${q}`, {
      method: "POST",
      headers: { authorization: `Bearer ${token}`, "content-type": "application/octet-stream", "content-length": String(statSync(file).size) },
      body: createReadStream(file),
      duplex: "half",
      signal: AbortSignal.timeout(3600000),
    });
    const out = await r.json().catch(() => ({}));
    if (!r.ok) return json(res, r.status, { error: out.error || `upload failed (${r.status})` }), true;
    // This computer keeps a copy, so it opens at once and edits sync back.
    const f = copyPath(out);
    mkdirSync(dirname(f), { recursive: true });
    copyFileSync(file, f);
    remember(out, f);
    await syncOnce();
    return json(res, 200, out), true;
  }
  // Download (if needed) and give the local copy, to open with its app.
  const loc = /^\/api\/files\/([0-9a-f-]{36})\/local$/.exec(path);
  if (loc && m === "GET") {
    const { path: f } = await localFile(loc[1]);
    const u = (p) => "file:///" + p.replace(/\\/g, "/").replace(/^\//, "");
    return json(res, 200, { path: f, url: u(f), folder: u(dirname(f)) }), true;
  }
  // Show the copy selected in Explorer (Finder / the file manager elsewhere).
  const rev = /^\/api\/files\/([0-9a-f-]{36})\/reveal$/.exec(path);
  if (rev && m === "POST") {
    const { path: f } = await localFile(rev[1]);
    if (WIN) spawn("explorer.exe", ["/select,", f], { detached: true, stdio: "ignore" }).unref();
    else spawn("xdg-open", [dirname(f)], { detached: true, stdio: "ignore" }).unref();
    return json(res, 200, { path: f }), true;
  }
  // "Download…": a copy saved where the user chose ({ path }), straight from
  // the server (or this computer's open copy, when it is current). Not kept
  // track of: it is the user's file now.
  const save = /^\/api\/files\/([0-9a-f-]{36})\/save$/.exec(path);
  if (save && m === "POST") {
    const b = await readBody(req);
    const to = decodeURIComponent(String(b.path || "").replace(/^file:\/\/\/?/, WIN ? "" : "/"));
    if (!to || !existsSync(dirname(to))) return json(res, 400, { error: "Choose a folder that exists." }), true;
    const row = store.get("files", save[1]);
    if (!row || row.deleted) return json(res, 404, { error: "That file is gone." }), true;
    const have = index[row.id];
    if (have && existsSync(have.path) && have.updated_at >= row.updated_at) {
      copyFileSync(have.path, to);
      return json(res, 200, { path: to }), true;
    }
    const { server, token } = config();
    if (!server) return json(res, 401, { error: "Sign in to download files." }), true;
    const r = await fetch(`${server}/api/files/${row.id}/raw`, { headers: { authorization: `Bearer ${token}` }, signal: AbortSignal.timeout(3600000) });
    if (!r.ok) return json(res, 502, { error: `Could not download it (${r.status}).` }), true;
    const tmp = to + ".part";
    try {
      await pipeline(Readable.fromWeb(r.body), createWriteStream(tmp));
      renameSync(tmp, to);
    } catch (e) {
      rmSync(tmp, { force: true });
      throw e;
    }
    return json(res, 200, { path: to }), true;
  }
  if (path === "/api/ai" && m === "DELETE") return json(res, 200, await remote("/api/ai", { method: "DELETE" })), true;
  return false;
}

// --- the window (Windows) ---------------------------------------------------------
// The service starts the window as its own child, so Task Manager shows one
// Hourglass, not a window and a service side by side. The launcher asks for it
// with POST /api/window/show; a window hidden in the tray sees show_seq change
// and comes back. "Quit Hourglass" in the tray ends both.
const APP_ROOT = join(import.meta.dirname, "..");
let ui = null;
let showSeq = 0;

function windowExe() {
  for (const p of ["qt/bin/Hourglass.exe", "qt/bin/qml.exe", "qt/qml.exe"]) {
    const f = join(APP_ROOT, p);
    if (existsSync(f)) return f;
  }
  return null;
}

function openWindow() {
  showSeq++;
  if (ui) return { started: false };
  const exe = windowExe();
  if (!exe) return { error: "the Qt runtime is missing" };
  // menus=native: Qt's own tray menu opens and Windows closes it at once (the app
  // is not in the foreground); the native one stays up like any tray menu.
  ui = spawn(exe, ["--apptype", "widget", "-platform", "windows:menus=native", "-I", join(APP_ROOT, "app"), join(APP_ROOT, "app", "Main.qml"), "--", "--port", String(PORT), "--token", TOKEN], {
    cwd: APP_ROOT,
    stdio: "ignore",
    env: { ...process.env, QT_QUICK_CONTROLS_STYLE: "Basic" },
  });
  const child = ui;
  child.on("error", (e) => { log(`window: ${e.message}`); if (ui === child) ui = null; });
  child.on("exit", () => { if (ui === child) ui = null; });
  return { started: true };
}

function quitAll() {
  for (const id of [...ringing.keys()]) ring_stop(id);
  try { ui?.kill(); } catch {}
  process.exit(0);
}

// --- updates (Windows) ---------------------------------------------------------------
// marobotic.dev/apps/hourglass/latest.json says what the newest build is. The
// window shows "Update available"; Install downloads that setup.exe, checks its
// SHA-256 against the feed, runs it silently and exits - the installer replaces
// the files and starts Hourglass again. HOURGLASS_UPDATE_FEED points tests at
// another feed; "off" turns checking off.
const UPDATE_FEED = process.env.HOURGLASS_UPDATE_FEED || "https://marobotic.dev/apps/hourglass/latest.json";
const update = { checked_at: null, latest: null, installing: false, error: null };

// "0.2.10" > "0.2.9": compared number by number.
function newer(a, b) {
  const pa = String(a).split(".").map(Number), pb = String(b).split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d > 0;
  }
  return false;
}

async function checkUpdate() {
  if (!WIN || UPDATE_FEED === "off") return;
  try {
    const r = await fetch(UPDATE_FEED, { signal: AbortSignal.timeout(15000), headers: { "cache-control": "no-cache" } });
    if (!r.ok) throw new Error(`feed ${r.status}`);
    const feed = await r.json();
    const win = feed.windows;
    update.latest = win && win.url && newer(feed.version, VERSION)
      ? { version: feed.version, notes: feed.notes || "", url: win.url, sha256: win.sha256 || "", size: win.size || 0 }
      : null;
    update.error = null;
  } catch (e) {
    update.error = e.message;
  }
  update.checked_at = Date.now();
}

async function installUpdate() {
  const u = update.latest;
  if (!u) throw Object.assign(new Error("no update to install"), { status: 409 });
  if (update.installing) return;
  update.installing = true;
  try {
    const r = await fetch(u.url, { signal: AbortSignal.timeout(1800000) });
    if (!r.ok) throw new Error(`download ${r.status}`);
    const file = join(tmpdir(), `Hourglass-${u.version}-setup.exe`);
    await pipeline(Readable.fromWeb(r.body), createWriteStream(file));
    if (u.sha256) {
      const hash = createHash("sha256").update(readFileSync(file)).digest("hex");
      if (hash.toLowerCase() !== u.sha256.toLowerCase()) { rmSync(file, { force: true }); throw new Error("the download did not match the release"); }
    }
    // The installer closes this service and the window itself, then starts Hourglass again.
    spawn(file, ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART", "/RELAUNCH"], { detached: true, stdio: "ignore" }).unref();
    setTimeout(quitAll, 500);
  } catch (e) {
    update.installing = false;
    update.error = e.message;
    throw Object.assign(e, { status: 502 });
  }
}

if (WIN) {
  setTimeout(() => checkUpdate(), 20000);
  setInterval(() => checkUpdate(), 6 * 3600 * 1000);
}

async function extra(req, res, url, path) {
  if (await driveRoutes(req, res, url, path)) return true;
  if (WIN && path === "/api/window" && req.method === "GET") return json(res, 200, { show_seq: showSeq, open: !!ui }), true;
  if (WIN && path === "/api/window/show" && req.method === "POST") {
    const r = openWindow();
    return json(res, r.error ? 500 : 200, r), true;
  }
  if (WIN && path === "/api/update" && req.method === "GET") {
    if (url.searchParams.get("check") === "1") await checkUpdate();
    return json(res, 200, { current: VERSION, ...update }), true;
  }
  if (WIN && path === "/api/update/install" && req.method === "POST") {
    await installUpdate();
    return json(res, 200, { ok: true }), true;
  }
  if (WIN && path === "/api/quit" && req.method === "POST") {
    json(res, 200, { ok: true });
    setTimeout(quitAll, 200);
    return true;
  }
  if (path === "/api/app" && req.method === "GET") {
    return json(res, 200, {
      theme: theme(),
      sync: { ...sync, server: config().server ?? null },
      ringing: [...ringing.values()].map(({ stop, ...r }) => r),
      settings: service.settings(),
      account: account(),
      tz_offset_min: tzOffsetMin(),
      version: VERSION,
      update: update.latest ? { version: update.latest.version, notes: update.latest.notes, installing: update.installing } : null,
    }), true;
  }
  if (path === "/api/ring/stop" && req.method === "POST") {
    const id = url.searchParams.get("id");
    const ids = id ? [id] : [...ringing.keys()];
    return json(res, 200, { stopped: ids.filter(ring_stop) }), true;
  }
  if (path === "/api/ring/snooze" && req.method === "POST") {
    const id = url.searchParams.get("id");
    const r = ringing.get(id);
    if (!r) return json(res, 404, { error: "not ringing" }), true;
    ring_stop(id);
    const t = service.startTimer({ minutes: Number(url.searchParams.get("minutes") || 5), label: `${r.label} (snoozed)` });
    return json(res, 200, t), true;
  }
  if (path === "/api/account" && req.method === "GET") return json(res, 200, account()), true;
  if (path === "/api/account/login" && req.method === "POST") {
    const b = await readBody(req);
    const out = await remote("/auth/login", { method: "POST", body: { email: b.email, password: b.password }, bearer: null });
    return json(res, 200, await signIn(out.session, out.email)), true;
  }
  if (path === "/api/account/register" && req.method === "POST") {
    const b = await readBody(req);
    const out = await remote("/auth/register", { method: "POST", body: { email: b.email, password: b.password }, bearer: null });
    if (!out.session) throw Object.assign(new Error("account created: sign in with it"), { status: 400 });
    return json(res, 200, await signIn(out.session, out.email || String(b.email).toLowerCase())), true;
  }
  // Forgot password: the server mails a reset link (same answer for any email).
  if (path === "/api/account/forgot" && req.method === "POST") {
    const b = await readBody(req);
    await remote("/auth/forgot", { method: "POST", body: { email: b.email }, bearer: null });
    return json(res, 200, { ok: true }), true;
  }
  // The account's personal AI key and links (made on the server).
  if (path === "/api/ai" && (req.method === "GET" || req.method === "POST")) {
    return json(res, 200, await remote("/api/ai", { method: req.method, body: req.method === "POST" ? {} : undefined })), true;
  }
  if (path === "/api/account/logout" && req.method === "POST") return json(res, 200, await signOut()), true;
  if (path === "/api/ringtones" && req.method === "GET") {
    return json(res, 200, service.listRingtones().map((r) => ({ ...r, ready: r.kind === "builtin" || existsSync(customFile(r.id)) }))), true;
  }
  // Upload a local audio file: the server cuts and stores it, then it syncs here.
  if (path === "/api/ringtones/upload" && req.method === "POST") {
    const b = await readBody(req);
    const file = decodeURIComponent(String(b.path || "").replace(/^file:\/\//, ""));
    if (!existsSync(file)) return json(res, 400, { error: "file not found" }), true;
    const name = b.name || file.split(/[\\/]/).pop();
    const row = await remote(`/api/ringtones/upload?select=1&name=${encodeURIComponent(name)}`, { method: "POST", raw: readFileSync(file) });
    await syncOnce();
    return json(res, 201, row), true;
  }
  const del = /^\/api\/ringtones\/([0-9a-f-]{36})$/.exec(path);
  if (del && req.method === "DELETE") return json(res, 200, service.removeRingtone({ ringtone_id: del[1] })), true;
  // Plays a ringtone once, for choosing one in Settings.
  if (path === "/api/ring/preview" && req.method === "POST") {
    playOnce(soundFile(url.searchParams.get("name")));
    return json(res, 200, { ok: true }), true;
  }
  // The assistant runs on the server (opencode there, on this account's data);
  // the sidecar only carries the account's session to it.
  if (path.startsWith("/api/assistant")) {
    if (!config().token) {
      if (req.method === "GET") return json(res, 200, { enabled: false, reason: "Sign in to use the assistant.", messages: [] }), true;
      return json(res, 401, { error: "Sign in to use the assistant." }), true;
    }
    const body = req.method === "POST" ? await readBody(req) : undefined;
    return json(res, 200, await remote(path, { method: req.method, body })), true;
  }
  if (path === "/api/sync/now" && req.method === "POST") {
    await syncOnce();
    return json(res, 200, sync), true;
  }
  return false;
}

async function readBody(req) {
  let b = "";
  for await (const c of req) b += c;
  try { return JSON.parse(b || "{}"); } catch { return {}; }
}

const handler = createHandler({ store, service, token: TOKEN, extra });
// Qt's XMLHttpRequest drops the body of a 407, 409 or 410 and reports status 0,
// which the window can only call "service is not running": send those as 400.
const QT_UNREADABLE = new Set([407, 409, 410]);

createServer((req, res) => {
  const writeHead = res.writeHead;
  res.writeHead = (status, ...rest) => writeHead.call(res, QT_UNREADABLE.has(status) ? 400 : status, ...rest);
  const url = new URL(req.url, "http://local");
  if (url.pathname.startsWith("/files/")) return serveFile(req, res, url);
  if (url.pathname.startsWith("/thumbs/")) return serveThumb(req, res, url);
  return handler(req, res);
}).listen(PORT, "127.0.0.1", async () => {
  log(`hourglassd on http://127.0.0.1:${PORT} (data ${DATA_DIR}, tz ${service.tz})`);
  config();
  await adoptMusicSession();
  scheduleSync(0);
});

